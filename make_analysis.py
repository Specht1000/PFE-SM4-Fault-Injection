"""Generate a didactic 'algorithm analysis' PDF into docs/ with one command.

    python make_analysis.py

It computes real data from src/aes.py and src/sm4.py (S-box tables, avalanche /
diffusion per round), writes docs/latex/analysis/data.tex, then compiles the
standalone document docs/latex/algorithm_analysis.tex into
docs/Algorithm_Analysis.pdf using the same portable Tectonic compiler as
build_pdf.py (downloaded on first run).

This document only visualizes the ciphers (structure diagrams, the S-boxes, and
diffusion statistics). It does not contain fault injection or key recovery.
"""
import contextlib
import io
from pathlib import Path
import shutil
import struct
import sys

ROOT = Path(__file__).resolve().parent
SRC = ROOT / "src"
LATEX = ROOT / "docs" / "latex"
DATA = LATEX / "analysis" / "data.tex"

sys.path.insert(0, str(SRC))
import aes  # noqa: E402

aes.STEP_BY_STEP = False
aes.SHOW_CALCULATIONS = False
with contextlib.redirect_stdout(io.StringIO()):  # sm4.py prints a demo on import
    import sm4  # noqa: E402

# Public test vectors (the ciphers' own documented examples).
AES_KEY = bytes.fromhex("000102030405060708090a0b0c0d0e0f")
AES_PT = bytes.fromhex("00112233445566778899aabbccddeeff")
SM4_KEY = bytes.fromhex("0123456789abcdeffedcba9876543210")
SM4_PT = bytes.fromhex("0123456789abcdeffedcba9876543210")


def hamming_bits(a, b):
    return sum(bin(x ^ y).count("1") for x, y in zip(a, b))


def hamming_bytes(a, b):
    return sum(x != y for x, y in zip(a, b))


def aes_round_states(plaintext, key):
    """State (16 bytes) after each round 0..10, computed silently."""
    state = aes.bytes_to_state(plaintext)
    round_keys = aes.key_expansion(key)
    states = []
    aes.add_round_key(state, round_keys[0])
    states.append(aes.state_to_bytes(state))
    for r in range(1, 10):
        aes.sub_bytes(state)
        aes.shift_rows(state)
        aes.mix_columns(state)
        aes.add_round_key(state, round_keys[r])
        states.append(aes.state_to_bytes(state))
    aes.sub_bytes(state)
    aes.shift_rows(state)
    aes.add_round_key(state, round_keys[10])
    states.append(aes.state_to_bytes(state))
    return states


def sm4_round_states(plaintext, key):
    """State (16 bytes) after each of the 32 SM4 rounds, computed silently."""
    x = list(struct.unpack(">4I", plaintext))
    round_keys = sm4.key_expansion(key)
    states = []
    for i in range(32):
        x[0], x[1], x[2], x[3] = sm4.round(x, round_keys[i])
        states.append(struct.pack(">4I", *x))
    return states


def coords(values, start=0):
    """pgfplots coordinate list: '(x,y)(x,y)...'."""
    return "".join(f"({start + i},{v})" for i, v in enumerate(values))


def sbox_grid(table):
    """256 \\sbc{col}{row}{shade}{HH} cell macro calls for a 16x16 heatmap."""
    lines = []
    for index, value in enumerate(table):
        row, col = index // 16, index % 16
        shade = 12 + round(value / 255 * 78)  # blue!12 (low) .. blue!90 (high)
        lines.append(f"\\sbc{{{col}}}{{{row}}}{{{shade}}}{{{value:02X}}}")
    return "\n".join(lines)


def tex_escape_list(values):
    return ", ".join(str(v) for v in values)


def main():
    # --- AES data ---
    base = aes_round_states(AES_PT, AES_KEY)
    flipped = aes_round_states(bytes([AES_PT[0] ^ 1]) + AES_PT[1:], AES_KEY)
    aes_bits = [hamming_bits(a, b) for a, b in zip(base, flipped)]
    aes_bytes = [hamming_bytes(a, b) for a, b in zip(base, flipped)]
    aes_cipher = base[-1].hex().upper()
    aes_fixed = [i for i, v in enumerate(aes.SBOX) if i == v]

    # --- SM4 data ---
    sbase = sm4_round_states(SM4_PT, SM4_KEY)
    sflip = sm4_round_states(bytes([SM4_PT[0] ^ 1]) + SM4_PT[1:], SM4_KEY)
    sm4_bits = [hamming_bits(a, b) for a, b in zip(sbase, sflip)]
    sm4_cipher = sbase[-1].hex().upper()
    sm4_fixed = [i for i, v in enumerate(sm4.SBOX) if i == v]

    DATA.parent.mkdir(parents=True, exist_ok=True)
    out = []
    out.append("% Auto-generated by make_analysis.py. Do not edit by hand.")
    out.append(f"\\def\\AEScipher{{{aes_cipher}}}")
    out.append(f"\\def\\SMfourcipher{{{sm4_cipher}}}")
    out.append(f"\\def\\AESfixed{{{'none' if not aes_fixed else tex_escape_list(aes_fixed)}}}")
    out.append("\\def\\SMfourfixed{%s}" % (
        "none" if not sm4_fixed else ", ".join(f"0x{v:02X} ({v})" for v in sm4_fixed)))
    out.append(f"\\def\\AESbitsreached{{{aes_bits[1]}}}")  # bits changed after round 1
    out.append(f"\\def\\AESbitsfull{{{aes_bits[2]}}}")     # after round 2
    out.append(f"\\def\\AESavalanche{{{coords(aes_bits, 0)}}}")
    out.append(f"\\def\\AESbytes{{{coords(aes_bytes, 0)}}}")
    out.append(f"\\def\\SMfouravalanche{{{coords(sm4_bits, 1)}}}")
    out.append(f"\\def\\AESsboxgrid{{%\n{sbox_grid(aes.SBOX)}}}")
    out.append(f"\\def\\SMfoursboxgrid{{%\n{sbox_grid(list(sm4.SBOX))}}}")
    DATA.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"Data written: {DATA}")
    print(f"  AES avalanche (bits/round): {aes_bits}")
    print(f"  SM4 avalanche (bits/round): {sm4_bits}")

    # --- Compile (reuses build_pdf's portable Tectonic) ---
    try:
        import build_pdf
    except Exception as error:  # pragma: no cover
        print(f"Could not import build_pdf.py for compilation: {error}")
        print("Data is ready; compile docs/latex/algorithm_analysis.tex manually.")
        return 1
    import os
    import subprocess
    compiler = build_pdf.find_compiler()
    outdir = ROOT / ".build" / "latex" / "analysis"
    outdir.mkdir(parents=True, exist_ok=True)
    env = os.environ.copy()
    env["TECTONIC_CACHE_DIR"] = str(ROOT / ".tools" / "tectonic" / "cache")
    command = [str(compiler), "-X", "compile", "--untrusted", "--keep-logs",
               "--outdir", str(outdir), "algorithm_analysis.tex"]
    print("Compiling algorithm_analysis.tex (first run also downloads LaTeX packages)...")
    status = subprocess.run(command, cwd=LATEX, env=env).returncode
    generated = outdir / "algorithm_analysis.pdf"
    if status != 0 or not generated.is_file():
        print("Compilation failed. See the log in", outdir)
        return 1
    destination = ROOT / "docs" / "Algorithm_Analysis.pdf"
    shutil.copyfile(generated, destination)
    print(f"\nPDF generated: {destination}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
