static uint32_t load_be32(const uint8_t *data)
{
    /* Cast before shifting: uint8_t otherwise promotes to signed int. */
    return ((uint32_t)data[0] << 24) | ((uint32_t)data[1] << 16) | ((uint32_t)data[2] << 8) | (uint32_t)data[3];
}

static void store_be32(uint8_t *data, uint32_t value)
{
    data[0] = (uint8_t)(value >> 24);
    data[1] = (uint8_t)(value >> 16);
    data[2] = (uint8_t)(value >> 8);
    data[3] = (uint8_t)value;
}

static uint32_t rotl32(uint32_t value, unsigned int count)
{
    /* All callers use fixed counts strictly between zero and 32. */
    return (value << count) | (value >> (32u - count));
}

static uint32_t tau(uint32_t value)
{
    /* Four independent byte substitutions; no inverse S-box is required. */
    uint32_t result = 0;

    for (unsigned int byte = 0; byte < 4; byte++) {
        unsigned int shift = 24u - 8u * byte;
        uint8_t input = (uint8_t)(value >> shift);
        result |= (uint32_t)SBOX[input] << shift;
    }

    return result;
}

static uint32_t linear(uint32_t value)
{
    return value ^ rotl32(value, 2) ^ rotl32(value, 10) ^ rotl32(value, 18) ^ rotl32(value, 24);
}

static uint32_t linear_key(uint32_t value)
{
    /* Key expansion uses L-prime, rather than the data transformation L. */
    return value ^ rotl32(value, 13) ^ rotl32(value, 23);
}

void sm4_set_key(sm4_context *context, const uint8_t key[SM4_BLOCK_SIZE])
{
    uint32_t state[4];

    for (unsigned int word = 0; word < 4; word++) {
        state[word] = load_be32(key + 4u * word) ^ FK[word];
    }

    for (unsigned int round = 0; round < SM4_ROUNDS; round++) {
        uint32_t input = state[1] ^ state[2] ^ state[3] ^ CK[round];
        uint32_t next = state[0] ^ linear_key(tau(input));
        context->rk[round] = next;
        state[0] = state[1];
        state[1] = state[2];
        state[2] = state[3];
        state[3] = next;
    }
}

void sm4_crypt_block(const sm4_context *context, const uint8_t input[SM4_BLOCK_SIZE], uint8_t output[SM4_BLOCK_SIZE], uint8_t decrypt, sm4_round_hook hook)
{
    uint32_t state[4];

    for (unsigned int word = 0; word < 4; word++) {
        state[word] = load_be32(input + 4u * word);
    }

    for (unsigned int round = 0; round < SM4_ROUNDS; round++) {
        unsigned int key_index = round;

        if (decrypt) {
            key_index = SM4_ROUNDS - 1u - round;
        }

        if (hook != 0) {
            hook((uint8_t)round, 1);
        }

        uint32_t a = state[1] ^ state[2] ^ state[3] ^ context->rk[key_index];
        uint32_t b = tau(a);
        uint32_t next = state[0] ^ linear(b);

        state[0] = state[1];
        state[1] = state[2];
        state[2] = state[3];
        state[3] = next;

        if (hook != 0) {
            hook((uint8_t)round, 0);
        }
    }

    /* Reverse WORD order at the end; preserve big-endian bytes within words. */
    for (unsigned int word = 0; word < 4; word++) {
        store_be32(output + 4u * word, state[3u - word]);
    }
}
